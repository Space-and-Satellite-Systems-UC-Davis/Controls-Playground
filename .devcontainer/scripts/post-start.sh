#!/usr/bin/env bash
# devcontainer postStartCommand: verify the GPU path and make it self-correcting.
set -u

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
DISPLAY_NUM="${DISPLAY:-:0}"
DISPLAY_NUM="${DISPLAY_NUM#:}"
DISPLAY_NUM="${DISPLAY_NUM%%.*}"
PROFILE=/etc/profile.d/10-devcontainer-gpu.sh

log() { printf '[post-start] %s\n' "$*"; }

# Qt/GLib expect a private runtime dir; containerEnv points at /tmp/runtime-root.
if [ -n "${XDG_RUNTIME_DIR:-}" ] && [ ! -d "$XDG_RUNTIME_DIR" ]; then
  mkdir -p "$XDG_RUNTIME_DIR" 2>/dev/null && chmod 700 "$XDG_RUNTIME_DIR" 2>/dev/null \
    && log "created XDG_RUNTIME_DIR=$XDG_RUNTIME_DIR"
fi

# --- 1. GPU bridge -----------------------------------------------------------
if [ -e /dev/dxg ]; then
  GPU_MODE=wsl
  log "WSL vGPU present (/dev/dxg) -> Mesa d3d12 (any vendor)"
  export GALLIUM_DRIVER="${GALLIUM_DRIVER:-d3d12}"
  case ":${LD_LIBRARY_PATH:-}:" in
    */usr/lib/wsl/lib:*) ;;
    *) export LD_LIBRARY_PATH="/usr/lib/wsl/lib${LD_LIBRARY_PATH:+:${LD_LIBRARY_PATH}}" ;;
  esac
elif [ -d /dev/dri ]; then
  GPU_MODE=native
  log "native DRM device present (/dev/dri)"
  unset GALLIUM_DRIVER
else
  GPU_MODE=none
  log "no GPU device found (/dev/dxg, /dev/dri) -> software rendering (llvmpipe)"
  unset GALLIUM_DRIVER
fi

# --- 2. publish the decision to login shells ---------------------------------
if mkdir -p "$(dirname "$PROFILE")" 2>/dev/null && [ -w "$(dirname "$PROFILE")" ]; then
  {
    echo "# generated by .devcontainer/scripts/post-start.sh on every start"
    case "$GPU_MODE" in
      wsl)
        printf 'export GALLIUM_DRIVER=%s\n' "${GALLIUM_DRIVER:-d3d12}"
        printf '%s\n' 'export LD_LIBRARY_PATH="/usr/lib/wsl/lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"'
        [ -n "${MESA_D3D12_DEFAULT_ADAPTER_NAME:-}" ] && \
          printf 'export MESA_D3D12_DEFAULT_ADAPTER_NAME=%s\n' "$MESA_D3D12_DEFAULT_ADAPTER_NAME"
        ;;
      *)
        printf '%s\n' 'unset GALLIUM_DRIVER'
        ;;
    esac
    true   # the group's exit status must not depend on an optional export above
  } >"$PROFILE" 2>/dev/null && log "wrote $PROFILE (platform: ${GPU_MODE})"
fi

# --- 3. display --------------------------------------------------------------
# Default: WSLg's own X/Wayland sockets, so windows appear on the Windows desktop.
# Fallback for browser/remote access: GZ_USE_VNC=1 starts the container's own
# server on :1 (then run GUI apps with DISPLAY=:1).
if [ "${GZ_USE_VNC:-0}" = "1" ]; then
  log "GZ_USE_VNC=1 -> starting container VNC on :1 (use DISPLAY=:1 for GUI apps)"
  bash "${SCRIPT_DIR}/start-vnc.sh" || true
else
  [ -S "/tmp/.X11-unix/X${DISPLAY_NUM}" ] \
    || log "WARNING: no X socket for display :${DISPLAY_NUM}; is /tmp/.X11-unix mounted?"
fi

# --- 4. record which renderer the GL path actually yields --------------------
if command -v glxinfo >/dev/null 2>&1; then
  glxinfo -B 2>/dev/null \
    | grep -E 'Device|Accelerated|OpenGL renderer' >/tmp/gpu-check.log 2>&1 || true
else
  echo "glxinfo missing (apt install mesa-utils)" >/tmp/gpu-check.log
fi

if grep -q 'Accelerated: yes' /tmp/gpu-check.log 2>/dev/null; then
  log "GPU rendering active on :${DISPLAY_NUM}: $(grep -m1 'OpenGL renderer' /tmp/gpu-check.log)"
else
  log "WARNING: software rendering on :${DISPLAY_NUM}. Details: /tmp/gpu-check.log"
  log "         WSL: 'wsl --shutdown' from Windows, then reopen. No browser access?"
  log "         Try GZ_USE_VNC=1 to use the container's own VNC server."
fi
